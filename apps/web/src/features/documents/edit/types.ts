/** Что редактор отдаёт окну сохранения: есть ли правки, заметка «что изменилось» и как собрать файл */
export interface SaveSpec {
  changed: boolean
  /** Заметка к версии, собранная по правкам */
  summary: string
  /** Предупреждения, которые стоит показать перед сохранением */
  notes: string[]
  /** Если задано, без отметки «понимаю» сохранить нельзя (например, диаграммы Excel пропадут) */
  ack?: string
  /** Собирает итоговый файл (долго для больших таблиц, поэтому по кнопке) */
  build: () => Promise<Blob>
  mime: string
}

export interface EditorHost {
  /** Есть несохранённые изменения */
  setDirty: (dirty: boolean) => void
  /** Редактор сообщает, как собрать результат; вызывается при каждой отрисовке */
  bind: (get: () => SaveSpec) => void
}
